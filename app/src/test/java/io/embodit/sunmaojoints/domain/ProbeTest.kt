package io.embodit.sunmaojoints.domain

import org.junit.Test
import java.io.File

/**
 * Writes domain/JointTable.kt from the 2 mm voxel sweep (design lessonRules.authoring: the build station's number
 * table). Runs only when asked: `PROBE=1 gradlew :app:testDebugUnitTest --tests "*ProbeTest*"`. U1 then checks the
 * table against an independent 4 mm sweep on every build.
 */
class ProbeTest {
    private fun f(v: Float) = "%.2ff".format(java.util.Locale.ROOT, v)
    private fun box(b: Aabb?) = if (b == null) "null" else "Aabb(V3(${f(b.lo.x)}, ${f(b.lo.y)}, ${f(b.lo.z)}), V3(${f(b.hi.x)}, ${f(b.hi.y)}, ${f(b.hi.z)}))"

    @Test
    fun writeTable() {
        if (System.getenv("PROBE") == null) return
        val size = 0.2f
        val sb = StringBuilder()
        sb.appendLine("package io.embodit.sunmaojoints.domain")
        sb.appendLine()
        sb.appendLine("/**")
        sb.appendLine(" * GENERATED by ProbeTest from the 2 mm voxel sweep (never edit by hand). Per lesson, step, candidate: where it")
        sb.appendLine(" * stops (cm from home; 0 = all the way in), where it touches (joint frame, cm) and, for a trap, where the next")
        sb.appendLine(" * piece then stops. U1–U3 re-check every row with a 4 mm sweep.")
        sb.appendLine(" */")
        sb.appendLine("object JointTable {")
        sb.appendLine("    class Row(val stopCm: Float, val contact: Aabb?, val bounceCm: Float = 0f, val bounceContact: Aabb? = null)")
        sb.appendLine()
        sb.appendLine("    val ROWS: List<List<List<Row>>> = listOf(")
        for (l in Joints.ALL) {
            sb.appendLine("        listOf( // ${l.n} ${l.id}")
            for ((k, st) in l.steps.withIndex()) {
                val standing = Sweep.standing(l, k)
                sb.appendLine("            listOf(")
                for (c in st.cands) {
                    val r = Sweep.push(l, c, standing, size)
                    if (c.outcome == Outcome.TRAP) {
                        val b = Sweep.push(l, st.fit, standing + l.piece(c.piece), size)
                        sb.appendLine("                Row(${f(r.stopCm)}, ${box(r.contact)}, ${f(b.stopCm)}, ${box(b.contact)}), // ${c.piece} ${c.from} ${c.outcome}")
                    } else sb.appendLine("                Row(${f(r.stopCm)}, ${box(r.contact)}), // ${c.piece} ${c.from} ${c.outcome}")
                }
                sb.appendLine("            ),")
            }
            sb.appendLine("        ),")
        }
        sb.appendLine("    )")
        sb.appendLine()
        sb.appendLine("    fun row(lesson: Int, step: Int, cand: Int): Row = ROWS[lesson][step][cand]")
        sb.appendLine("}")
        File("src/main/java/io/embodit/sunmaojoints/domain/JointTable.kt").writeText(sb.toString())
    }
}
